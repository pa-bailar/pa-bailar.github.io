// The colors for browsers without light-dark() (Safari before 17.5: iPhones on iOS 16, the iPhone 8 and X's last;
// the owner, 6 Oct 2026). Every semantic color in tokens.css is light-dark(<light>, <dark>); without the function
// the whole declaration is dropped and the page shows no colors at all. This writes src/styles/tokens-fallback.css:
// the same tokens with their light side on :root and their dark side on [data-theme="dark"], inside
// @supports not (light-dark()), so every browser that has the function skips it.
//
//   node scripts/light-dark-fallback.mjs   (after changing a light-dark() token; a test fails while it's stale)

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const STYLES = path.join(path.dirname(fileURLToPath(import.meta.url)), "../src/styles");
export const TOKENS = path.join(STYLES, "tokens.css");
export const FALLBACK = path.join(STYLES, "tokens-fallback.css");

/** `value` with each light-dark(a, b) replaced by its `side` (a or b), parentheses and nesting respected. */
export function pickSide(value, side) {
  let out = "";
  let at = 0;
  for (;;) {
    const start = value.indexOf("light-dark(", at);
    if (start < 0) return out + value.slice(at);
    out += value.slice(at, start);
    let depth = 0;
    let comma = -1;
    let end = -1;
    for (let i = start + "light-dark".length; i < value.length; i++) {
      const char = value[i];
      if (char === "(") depth++;
      else if (char === ")" && --depth === 0) {
        end = i;
        break;
      } else if (char === "," && depth === 1 && comma < 0) comma = i;
    }
    if (end < 0 || comma < 0) throw new Error(`unbalanced light-dark() in: ${value}`);
    const inner = side === "light" ? value.slice(start + "light-dark(".length, comma) : value.slice(comma + 1, end);
    out += pickSide(inner.trim(), side);
    at = end + 1;
  }
}

/** The custom properties of `css` whose value uses light-dark(): [name, value][], in order. */
export function lightDarkTokens(css) {
  const withoutComments = css.replace(/\/\*[\s\S]*?\*\//g, "");
  return [...withoutComments.matchAll(/(--[\w-]+)\s*:\s*([^;{}]*light-dark\([^;{}]*);/g)].map(([, name, value]) => [
    name,
    value.replace(/\s+/g, " ").trim(),
  ]);
}

/** The fallback stylesheet for `tokensCss`. */
export function fallbackCss(tokensCss) {
  const tokens = lightDarkTokens(tokensCss);
  const block = (side) => tokens.map(([name, value]) => `    ${name}: ${pickSide(value, side)};`).join("\n");
  return `/* Generated by scripts/light-dark-fallback.mjs from tokens.css: don't edit by hand (a test checks it's current).
   Browsers without light-dark() (Safari before 17.5, e.g. iOS 16) drop every color that uses it: these give them
   the light theme's values, and the dark ones under [data-theme="dark"]. Browsers with it skip this block. */

@supports not (color: light-dark(#000, #fff)) {
  :root {
${block("light")}
  }

  :root[data-theme="dark"] {
${block("dark")}
  }
}
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const css = fallbackCss(await readFile(TOKENS, "utf8"));
  await writeFile(FALLBACK, css);
  console.log(`tokens-fallback.css: ${lightDarkTokens(await readFile(TOKENS, "utf8")).length} tokens`);
}
